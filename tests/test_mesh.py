def test_abaqus_messy(tmp_path):
    text, ex = abaqus_messy()
    (tmp_path / "m.inp").write_text(text)
    m, w = record(read, tmp_path / "m.inp")
    assert w == ex["warnings"]
    assert np.array_equal(m.points, ex["points"])
    assert list(m.blocks) == ["hex8", "hex20"]
    cent = by_centroid(m)
    conn = np.concatenate([np.pad(c, ((0, 0), (0, 20 - c.shape[1])), constant_values=-1)
                           for c in m.blocks.values()])  # fmt: skip
    assert sorted(cent) == sorted(ex["elements"])
    for c, row in zip(cent, conn, strict=True):
        np.testing.assert_array_equal(m.points[row[row >= 0]], ex["elements"][c])
    assert dict(zip(cent, m.material.tolist(), strict=True)) == ex["material"]
    assert {c: o for c, o in zip(cent, m.orientation.tolist(), strict=True) if o} == ex[
        "orientation"
    ]
    assert sorted(m.node_sets) == sorted(ex["node_sets"])
    for k, v in ex["node_sets"].items():
        assert coords(m, m.node_sets[k]) == v
    assert sorted(m.element_sets) == sorted(ex["element_sets"])
    for k, v in ex["element_sets"].items():
        assert {cent[i] for i in m.element_sets[k]} == v


