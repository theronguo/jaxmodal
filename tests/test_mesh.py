def jacobian_oracle(x):
    """det(sum_i x_i grad N_i^T) at each REF corner, N_i = prod_d (1 + xi_id xi_d) / 8."""
    r = REF["hex8"]
    out = []
    for a in r:
        grad = np.empty((8, 3))
        for i, ri in enumerate(r):
            f = 1 + ri * a
            grad[i] = [ri[d] * np.prod(np.delete(f, d)) / 8 for d in range(3)]
        out.append(np.linalg.det(x.T @ grad))
    return np.array(out)


