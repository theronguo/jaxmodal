# --- 3. VTU round trip ----------------------------------------------------------------------


def three_type_mesh():
    """hex8 + hex20 + hex27 side by side sharing faces' corner nodes, non-identity numbering."""
    rng = np.random.default_rng(2)
    xi = {t: (REF[t] + 1) / 2 for t in REF}
    pts, blocks, index = [], {}, {}
    for shift, t in enumerate(["hex27", "hex8", "hex20"]):
        rows = []
        for p in xi[t] + [shift, 0, 0]:
            key = tuple(p)
            if key not in index:
                index[key] = len(pts)
                pts.append(p)
            rows.append(index[key])
        blocks[t] = np.array([rows])
    perm = rng.permutation(len(pts))  # non-identity numbering
    inv = np.argsort(perm)
    pts = np.array(pts)[perm] + rng.uniform(-0.01, 0.01, (len(pts), 3))
    blocks = {t: inv[blocks[t]] for t in ("hex8", "hex20", "hex27")}
    return mesh_of(pts, blocks, material=[12, -3, 4567], orientation=[7, 0, 2**31 - 1])


def test_vtu_round_trip(tmp_path):
    m = replace(three_type_mesh(), node_sets={"a": np.array([0, 1])})
    write(tmp_path / "m.vtu", m)
    raw = meshio.vtu.read(tmp_path / "m.vtu")
    assert sorted(raw.cell_data) == ["material", "orientation"]
    assert all(a.dtype == np.int64 for v in raw.cell_data.values() for a in v)
    r, w = record(read, tmp_path / "m.vtu")
    assert w == []
    assert np.array_equal(r.points, m.points)
    assert list(r.blocks) == list(m.blocks)
    for t in m.blocks:
        assert np.array_equal(r.blocks[t], m.blocks[t])
    assert np.array_equal(r.material, m.material) and np.array_equal(r.orientation, m.orientation)
    assert r.node_sets == {} and r.element_sets == {}


def test_vtu_float32_points(tmp_path):
    m = three_type_mesh()
    cells = [(n, m.blocks[t]) for n, t in [("hexahedron", "hex8"), ("hexahedron20", "hex20")]]
    meshio.vtu.write(tmp_path / "f.vtu", meshio.Mesh(m.points.astype(np.float32), cells))
    r = read(tmp_path / "f.vtu")
    assert r.points.dtype == np.float64
    used = np.unique(np.concatenate([m.blocks["hex8"].ravel(), m.blocks["hex20"].ravel()]))
    assert np.array_equal(r.points, m.points.astype(np.float32).astype(np.float64)[used])


