def test_ref_topology():
    r8 = REF["hex8"]
    assert (r8[0] == -1).all() and np.array_equal(r8[1] - r8[0], [2, 0, 0])
    bottom = r8[:4, :2]  # counter-clockwise seen from +z: positive signed area
    area = 0.5 * np.sum(
        bottom[:, 0] * np.roll(bottom[:, 1], -1) - np.roll(bottom[:, 0], -1) * bottom[:, 1]
    )
    assert area > 0 and (r8[:4, 2] == -1).all()
    assert np.array_equal(r8[4:], r8[:4] + [0, 0, 2])
    for p, e in enumerate(VTK_EDGES):
        assert np.array_equal(REF["hex20"][8 + p], r8[list(e)].mean(0))
    assert np.array_equal(REF["hex27"][:20], REF["hex20"])
    for p, axis, sign in zip(range(6), [0, 0, 1, 1, 2, 2], [-1, 1] * 3, strict=True):
        face = r8[r8[:, axis] == sign].mean(0)
        assert np.array_equal(REF["hex27"][20 + p], face)
    assert np.array_equal(REF["hex27"][26], [0, 0, 0])


# --- 2. Read orderings ----------------------------------------------------------------------


def xi_of(order):
    return np.array([REF["hex8"][list(c)].mean(0) for c in order])


def write_one(path, fmt, etype, swap=None):
    """Write one element in `fmt`'s documented order, nodes stored shuffled with sparse labels."""
    xi = xi_of(ORDER[fmt, etype])
    n = len(xi)
    x = affine(xi)
    store = np.random.default_rng(1).permutation(n)  # storage position -> format position
    label = 7 + 3 * np.arange(n)  # label of format position p
    conn = list(range(n))
    if swap:
        conn[swap[0]], conn[swap[1]] = conn[swap[1]], conn[swap[0]]
    if fmt == "msh":
        nodes = "\n".join(str(label[p]) for p in store) + "\n"
        nodes += "\n".join(" ".join(repr(float(v)) for v in x[p]) for p in store)
        path.write_text(
            "$MeshFormat\n4.1 0 8\n$EndMeshFormat\n"
            '$PhysicalNames\n1\n3 5 "solid"\n$EndPhysicalNames\n'
            "$Entities\n0 0 0 1\n1 -9 -9 -9 9 9 9 1 5 0\n$EndEntities\n"
            f"$Nodes\n1 {n} {label.min()} {label.max()}\n3 1 0 {n}\n{nodes}\n$EndNodes\n"
            f"$Elements\n1 1 4 4\n3 1 {GMSH_TYPE[etype.removesuffix('r')]} 1\n4 "
            + " ".join(str(label[p]) for p in conn)
            + "\n$EndElements\n"
        )
    elif fmt == "inp":
        nodes = "\n".join(f"{label[p]}, " + ", ".join(repr(float(v)) for v in x[p]) for p in store)
        ids = ["4"] + [str(label[p]) for p in conn]
        lines = ", ".join(ids[:16]) + ("," if len(ids) > 16 else "")
        if len(ids) > 16:
            lines += "\n" + ", ".join(ids[16:])
        path.write_text(f"*NODE\n{nodes}\n*ELEMENT, TYPE={ABAQUS_TYPE[etype]}\n{lines}\n")
    else:
        pos = np.argsort(store)  # format position -> storage position
        pts = " ".join(repr(float(v)) for p in store for v in x[p])
        path.write_text(
            '<?xml version="1.0"?>\n<VTKFile type="UnstructuredGrid" version="0.1" '
            'byte_order="LittleEndian">\n<UnstructuredGrid>\n'
            f'<Piece NumberOfPoints="{n}" NumberOfCells="1">\n<Points>\n'
            f'<DataArray type="Float64" NumberOfComponents="3" format="ascii">{pts}</DataArray>\n'
            "</Points>\n<Cells>\n"
            '<DataArray type="Int64" Name="connectivity" format="ascii">'
            + " ".join(str(pos[p]) for p in conn)
            + "</DataArray>\n"
            f'<DataArray type="Int64" Name="offsets" format="ascii">{n}</DataArray>\n'
            f'<DataArray type="UInt8" Name="types" format="ascii">{VTK_TYPE[etype]}</DataArray>\n'
            "</Cells>\n</Piece>\n</UnstructuredGrid>\n</VTKFile>\n"
        )
    return path


@pytest.mark.parametrize("fmt, etype", list(ORDER))
def test_read_ordering(tmp_path, fmt, etype):
    m = read(write_one(tmp_path / f"e.{fmt}", fmt, etype))
    etype = etype.removesuffix("r")
    assert list(m.blocks) == [etype]
    np.testing.assert_allclose(m.points[m.blocks[etype][0]], affine(REF[etype]), rtol=0, atol=1e-12)
    assert m.material.tolist() == [5 if fmt == "msh" else 0]
    assert (corner_jacobians(m)[etype] > 0).all()


@pytest.mark.parametrize("fmt", ["msh", "inp", "vtu"])
def test_ordering_mutant_fails(tmp_path, fmt):
    m = read(write_one(tmp_path / f"e.{fmt}", fmt, "hex20", swap=(8, 9)))
    assert not np.allclose(m.points[m.blocks["hex20"][0]], affine(REF["hex20"]))


def by_centroid(mesh):
    """Element coordinates keyed by rounded centroid, in global element order."""
    rows = np.concatenate([mesh.points[c[:, :8]].mean(1) for c in mesh.blocks.values()])
    return [tuple(np.round(r, 6)) for r in rows]


def coords(mesh, idx):
    return {tuple(np.round(mesh.points[i], 9)) for i in idx}


