def test_gmsh_messy():
    m, w = record(read, DATA / "gmsh_messy.msh")
    assert w == []
    assert list(m.blocks) == ["hex8"] and m.n_el == 16
    cent = np.array(by_centroid(m))
    assert np.array_equal(m.material, np.where(cent[:, 0] < 1, 7, 8))
    assert (m.orientation == 0).all() and m.element_sets == {}
    assert sorted(m.node_sets) == ["clamp", "edge", "physical_2_4"]
    x = m.points
    grid = {(a, b) for a in (0, 0.5, 1) for b in (0, 0.5, 1)}
    assert coords(m, m.node_sets["clamp"]) == {(0.0, y, z) for y, z in grid}
    assert coords(m, m.node_sets["physical_2_4"]) == {
        (s, y, z) for y, z in grid for s in (0.0, 2.0)
    }
    assert coords(m, m.node_sets["edge"]) == {(0.0, 0.0, z) for z in (0, 0.5, 1)}
    assert len(np.unique(x, axis=0)) == len(x)


def test_vtu_messy(tmp_path):
    """Blocks quad, hex20, quad, hex8, vertex; stray quad nodes mid-array; hex20 block first."""
    unit = (REF["hex20"] + 1) / 2
    pts = list(unit)  # hex20 on [0,1]^3: points 0..19
    stray = [[0, 0, 9], [1, 0, 9], [1, 1, 9], [0, 1, 9]]
    pts += stray  # 20..23, used only by a quad
    hex8 = [p + [1, 0, 0] for p in REF["hex8"] / 2 + 0.5]
    pts += hex8 + [p + [0, 0, 1] for p in hex8]  # 24..31, 32..39
    pts = np.array(pts, float)
    h20 = np.arange(20)[None]
    h8 = np.array([np.arange(24, 32), np.arange(32, 40)])
    quad = np.array([[0, 1, 2, 3]])
    cells = [("quad", quad + 20), ("hexahedron20", h20), ("quad", quad), ("hexahedron", h8),
             ("vertex", np.array([[5]]))]  # fmt: skip
    mat = [[0], [11], [0], [21, 22], [0]]
    meshio.vtu.write(tmp_path / "m.vtu", meshio.Mesh(pts, cells, cell_data={"material": mat}))
    m, w = record(read, tmp_path / "m.vtu")
    assert w == []
    assert list(m.blocks) == ["hex8", "hex20"] and m.offsets == {"hex8": 0, "hex20": 2}
    used = np.r_[0:20, 24:40]
    assert np.array_equal(m.points, pts[used])
    np.testing.assert_array_equal(m.points[m.blocks["hex20"][0]], unit)
    expect = {(0.5, 0.5, 0.5): 11, (1.5, 0.5, 0.5): 21, (1.5, 0.5, 1.5): 22}
    assert dict(zip(by_centroid(m), m.material.tolist(), strict=True)) == expect
    assert (m.orientation == 0).all()


